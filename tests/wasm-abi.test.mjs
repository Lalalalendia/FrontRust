import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const bytes=await readFile(process.argv[2]||'target/wasm32-unknown-unknown/release/rui_wasm.wasm');
const {instance}=await WebAssembly.instantiate(bytes,{});
const e=instance.exports;
const symbols=['uip_version','uip_select_at','uip_move_to','uip_set_width','uip_set_height','uip_undo','uip_reset','uip_get_x','uip_get_y','uip_get_width','uip_get_height','uip_is_selected','uip_document_revision','uip_scene_revision'];
for(const symbol of symbols)assert.equal(typeof e[symbol],'function',symbol);
assert.equal(e.uip_version(),1);
assert.deepEqual([e.uip_get_x(),e.uip_get_y(),e.uip_get_width(),e.uip_get_height()],[160,120,250,170]);
assert.equal(e.uip_move_to(200,130),0);
assert.equal(e.uip_select_at(200,180),1);
assert.equal(e.uip_document_revision(),0);
assert.equal(e.uip_select_at(200,180),0);
assert.equal(e.uip_move_to(180,130),2);
assert.equal(e.uip_move_to(180,130),0);
assert.equal(e.uip_document_revision(),1);
assert.equal(e.uip_set_width(260),2);
assert.equal(e.uip_undo(),2);
assert.equal(e.uip_get_width(),250);
assert.equal(e.uip_undo(),2);
assert.deepEqual([e.uip_get_x(),e.uip_get_y()],[160,120]);
assert.equal(e.uip_reset(),1);
assert.equal(e.uip_document_revision(),4);
console.log('PASS real WASM ABI');
